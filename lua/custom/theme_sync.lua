-- Shared terminal colours are published only for confirmed/restored themes.
local M = {}
local function directory() return vim.fn.stdpath 'state' .. '/terminal-theme' end
local function quote(value) return '"' .. value:gsub('\\', '\\\\'):gsub('"', '\\"'):gsub('%$', '\\$') .. '"' end
local function shell_quote(value) return "'" .. value:gsub("'", "'\\''") .. "'" end
local function atomic(path, lines)
  local tmp = path .. '.' .. vim.fn.getpid() .. '.tmp'
  vim.fn.writefile(lines, tmp)
  assert(vim.uv.fs_rename(tmp, path))
end

function M.render(palette, background, terminal, templates)
  local c = palette
  local ghostty = {
    '# Generated by Neovim theme picker.',
    'background = ' .. c.base,
    'foreground = ' .. c.text,
    'cursor-color = ' .. c.text,
    'cursor-text = ' .. c.base,
    'selection-background = ' .. c.surface0,
    'selection-foreground = ' .. c.text,
    'window-theme = ' .. background,
  }
  local fallback =
    { c.mantle, c.red, c.green, c.yellow, c.blue, c.lavender, c.sky, c.text, c.overlay1, c.red, c.green, c.yellow, c.blue, c.lavender, c.teal, c.text }
  for i = 0, 15 do
    ghostty[#ghostty + 1] = 'palette = ' .. i .. '=' .. (terminal[i + 1] or fallback[i + 1])
  end
  local fzf = '--color='
    .. background
    .. ',bg:'
    .. c.base
    .. ',fg:'
    .. c.text
    .. ',bg+:'
    .. c.surface0
    .. ',fg+:'
    .. c.text
    .. ',hl:'
    .. c.peach
    .. ',hl+:'
    .. c.peach
    .. ',border:'
    .. c.overlay1
    .. ',header:'
    .. c.blue
    .. ',info:'
    .. c.lavender
    .. ',prompt:'
    .. c.lavender
    .. ',pointer:'
    .. c.peach
    .. ',marker:'
    .. c.green
    .. ',spinner:'
    .. c.sky
    .. ',preview-bg:'
    .. c.mantle
    .. ',preview-fg:'
    .. c.text
  -- Recolour existing status formats without changing their content or layout.
  local replacements = {
    ['#1e1e2e'] = c.base,
    ['#181825'] = c.mantle,
    ['#11111b'] = c.mantle,
    ['#cdd6f4'] = c.text,
    ['#313244'] = c.surface0,
    ['#45475a'] = c.surface1,
    ['#585b70'] = c.overlay1,
    ['#a6adc8'] = c.subtext0,
    ['#89dceb'] = c.sky,
    ['#94e2d5'] = c.teal,
    ['#cba6f7'] = c.lavender,
    ['#f5c2e7'] = c.lavender,
    ['#f38ba8'] = c.red,
    ['#a6e3a1'] = c.green,
    ['#f9e2af'] = c.yellow,
    ['#89b4fa'] = c.blue,
    ['#fab387'] = c.peach,
  }
  local tmux = { '# Generated by Neovim theme picker.', 'set-option -g focus-events on' }
  for option, value in pairs(templates.options) do
    local recoloured = value
      :gsub('colour232', c.base)
      :gsub('colour255', c.text)
      :gsub('colour237', c.surface0)
      :gsub('#%x%x%x%x%x%x', function(hex) return replacements[hex:lower()] or hex end)
    tmux[#tmux + 1] = 'set-option -g ' .. option .. ' ' .. quote(recoloured)
  end
  for option, value in pairs {
    ['status-style'] = 'bg=' .. c.base .. ',fg=' .. c.text,
    ['pane-border-style'] = 'fg=' .. c.surface1,
    ['pane-active-border-style'] = 'fg=' .. c.lavender,
    ['popup-style'] = 'bg=' .. c.base .. ',fg=' .. c.text,
    ['popup-border-style'] = 'fg=' .. c.overlay1,
    ['message-style'] = 'bg=' .. c.surface0 .. ',fg=' .. c.text,
    ['message-command-style'] = 'bg=' .. c.surface0 .. ',fg=' .. c.text,
    ['mode-style'] = 'bg=' .. c.surface0 .. ',fg=' .. c.text,
  } do
    tmux[#tmux + 1] = 'set-option -g ' .. option .. ' ' .. quote(value)
  end
  -- SessionX caches its command-line options when the plugin loads. Update that
  -- cache too; explicit colours override inherited options in old shell sessions.
  local args = {}
  for _, arg in ipairs(templates.sessionx) do
    args[#args + 1] = shell_quote(arg)
  end
  args[#args + 1] = shell_quote(fzf)
  tmux[#tmux + 1] = 'set-option -g @sessionx-_built-fzf-opts ' .. quote('declare -a fzf_opts=(' .. table.concat(args, ' ') .. ')')
  tmux[#tmux + 1] = 'set-environment -g FZF_DEFAULT_OPTS ' .. quote(templates.fzf_base .. ' ' .. fzf)
  return { ghostty = ghostty, tmux = tmux, fzf = { fzf } }
end

function M.publish()
  local dir = directory()
  if vim.fn.filereadable(dir .. '/enabled') == 0 then return end
  local ok, err = pcall(function()
    local templates = vim.json.decode(table.concat(vim.fn.readfile(dir .. '/templates.json'), '\n'))
    local terminal = {}
    for i = 0, 15 do
      terminal[i + 1] = vim.g['terminal_color_' .. i]
    end
    local files = M.render(require('custom.theme').palette(), vim.o.background, terminal, templates)
    local old = vim.fn.filereadable(dir .. '/ghostty.conf') == 1 and vim.fn.readfile(dir .. '/ghostty.conf') or {}
    for name, lines in pairs(files) do
      atomic(dir .. '/' .. name .. '.conf', lines)
    end
    -- Also cover external programs launched from this Neovim process.
    vim.env.FZF_DEFAULT_OPTS = templates.fzf_base .. ' ' .. files.fzf[1]
    if vim.fn.executable 'tmux' == 1 then
      local server = vim.system({ 'tmux', 'list-sessions' }, { text = true }):wait(1000)
      if server.code == 0 then
        local result = vim.system({ 'tmux', 'source-file', dir .. '/tmux.conf' }, { text = true }):wait(2000)
        assert(result.code == 0, result.stderr)
      end
    end
    -- Ghostty >= 1.2 handles SIGUSR2 by reloading config, without reopening windows.
    if not vim.deep_equal(old, files.ghostty) and vim.fn.executable 'pkill' == 1 then
      local result = vim.system({ 'pkill', '-USR2', '-x', 'ghostty' }, { text = true }):wait(1000)
      assert(result.code == 0 or result.code == 1, result.stderr)
    end
  end)
  if not ok then vim.notify('Terminal theme sync failed: ' .. tostring(err), vim.log.levels.WARN) end
end

return M
